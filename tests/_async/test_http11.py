@pytest.mark.anyio
async def test_http11_connection_closed_midway_through_response():
    """
    Closing a response before it has been read to completion leaves
    the trailers empty, and closes the connection.
    """
    origin = httpcore.Origin(b"https", b"example.com", 443)
    stream = httpcore.AsyncMockStream(
        [
            b"HTTP/1.1 200 OK\r\n",
            b"Content-Type: plain/text\r\n",
            b"Transfer-Encoding: chunked\r\n",
            b"\r\n",
            b"5\r\nHello\r\n",
            b"8\r\n, world!\r\n",
            b"0\r\n",
            b"X-Checksum: abc123\r\n",
            b"\r\n",
        ]
    )
    async with httpcore.AsyncHTTP11Connection(origin=origin, stream=stream) as conn:
        async with conn.stream("GET", "https://example.com/") as response:
            body = response.aiter_stream()
            async for chunk in body:
                assert chunk == b"Hello"
                break
            await body.aclose()
            # The response was closed before the trailers were received.
            assert response.trailers == []

        assert not conn.is_idle()
        assert conn.is_closed()


